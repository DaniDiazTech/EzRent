const MONTHS = ['2026-04', '2026-05', '2026-06', '2026-07', '2026-08', '2026-09']

function history(opts: {
  canon: number
  admin: number
  predialAnual: number
  luz: number[]
  gas: number[]
  agua: number[] // bimestral: 0 en meses sin factura
  missedMonth?: number
}): MonthRecord[] {
  return MONTHS.map((month, i) => {
    const bills = [
      { type: 'administracion' as const, amount: opts.admin },
      { type: 'luz' as const, amount: opts.luz[i] },
      { type: 'gas' as const, amount: opts.gas[i] },
      ...(opts.agua[i] > 0 ? [{ type: 'agua' as const, amount: opts.agua[i] }] : []),
      // Predial diferido en cuotas mensuales (abril a noviembre, sistema SPAC)
      { type: 'predial' as const, amount: Math.round(opts.predialAnual / 8 / 100) * 100 },
    ]
    return { month, rentCollected: opts.canon + opts.admin, bills }
  })
}

